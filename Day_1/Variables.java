 public class Variables{
   public static void main(String[] args) {

     byte b = 127;
     System.out.println(b);
     int i = 56;
     System.out.println(i);
     char ch = 'a';
     System.out.println(ch);
     String s = "Prem mon";
     System.out.println(s);
     boolean var = true;
     System.out.println(var);
     double f = 3.14;
     System.out.println(f);
     
   }
 }