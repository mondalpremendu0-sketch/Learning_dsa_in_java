public class conditionalOperator{
  public static void main(String[] args) {
   // "==",">","<",">=","<=","!="
   //it return a Boolean type data
   int A = 5,B = 9;
   System.out.println((A == B));
   System.out.println((A != B));
   System.out.println((A <= B));
   System.out.println((A >= B));
   System.out.println((A > B));
   System.out.println((A < B));
   
  }
}