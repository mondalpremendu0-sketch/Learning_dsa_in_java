public class assigneOperators{
  public static void main(String[] args) {
   // "=","+=","-=","*=","/=","%="
   int a = 10;
   a = 34;
   System.out.println(a);
   a += 40;//a = a + 40;
   System.out.println(a);
   a -= 40;//a = a - 40;
   System.out.println(a);
   a *= 40;//a = a * 40;
   System.out.println(a);
   a /= 40;//a = a / 40;
   System.out.println(a);
   a %= 40;//a = a % 40;
   System.out.println(a);
  }
}